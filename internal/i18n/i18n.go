// Package i18n contains TailBuddy's English and Simplified Chinese UI strings.
package i18n

import "strings"

type Catalog struct{ Language string }

func New(locale string) Catalog {
	tag := strings.ToLower(strings.ReplaceAll(locale, "_", "-"))
	if tag == "zh" || strings.HasPrefix(tag, "zh-hans") || strings.HasPrefix(tag, "zh-cn") || strings.HasPrefix(tag, "zh-sg") {
		return Catalog{"zh-Hans"}
	}
	return Catalog{"en"}
}
func (c Catalog) T(key string) string {
	if c.Language == "zh-Hans" {
		if v, ok := zh[key]; ok {
			return v
		}
	}
	if v, ok := en[key]; ok {
		return v
	}
	return key
}

